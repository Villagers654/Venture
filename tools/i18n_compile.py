#!/usr/bin/env python3
"""Compiles the translations (i18n/*.po) into a C++ source the program links
(cmake/I18n.cmake runs this at build time), or checks them.

  python tools/i18n_compile.py --out catalogs.cpp   generate
  python tools/i18n_compile.py --check              validate every .po: it
      parses, its Plural-Forms is valid and every n picks an existing form,
      plural entries have that many forms, and each translation keeps exactly
      the source's {0} {1} arguments

Generating never fails on a translation's content: an entry that does not
check out is left out (English is shown), a catalog that cannot be read is
skipped, and catalogs translated less than min_completion (i18n/i18n.json)
are not compiled in. Only strings in the current POT are embedded.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import i18n_po as po  # noqa: E402

# Each language's name for itself, keyed by catalog file name (lowercase).
NATIVE_NAMES = {
    "af": "Afrikaans", "ar": "العربية", "bg": "Български", "ca": "Català", "cs": "Čeština",
    "da": "Dansk", "de": "Deutsch", "el": "Ελληνικά", "en_gb": "English (UK)", "eo": "Esperanto",
    "es": "Español", "es_419": "Español (Latinoamérica)", "es_mx": "Español (México)", "et": "Eesti",
    "eu": "Euskara", "fa": "فارسی", "fi": "Suomi", "fil": "Filipino", "fr": "Français", "ga": "Gaeilge",
    "gl": "Galego", "he": "עברית", "hi": "हिन्दी", "hr": "Hrvatski", "hu": "Magyar", "id": "Bahasa Indonesia",
    "it": "Italiano", "ja": "日本語", "ka": "ქართული", "kk": "Қазақ тілі", "ko": "한국어", "lt": "Lietuvių",
    "lv": "Latviešu", "ms": "Bahasa Melayu", "nb": "Norsk bokmål", "nl": "Nederlands", "nn": "Norsk nynorsk",
    "pl": "Polski", "pt": "Português", "pt_br": "Português (Brasil)", "pt_pt": "Português (Portugal)",
    "ro": "Română", "ru": "Русский", "sk": "Slovenčina", "sl": "Slovenščina", "sr": "Српски",
    "sr_latn": "Srpski", "sv": "Svenska", "th": "ไทย", "tr": "Türkçe", "uk": "Українська",
    "vi": "Tiếng Việt", "zh_hans": "简体中文", "zh_hant": "繁體中文",
}


def cxx_string(text: str) -> str:
    """A C++ string literal of the UTF-8 bytes (octal escapes, so the source
    file's encoding never matters), with a "sv" suffix to keep embedded NULs."""
    out = ['"']
    for b in text.encode("utf-8"):
        c = chr(b)
        if c in '"\\?':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    out.append('"sv')
    return "".join(out)


def load(cfg: po.Config):
    """(source catalog, [(code, path, catalog | None, error | None)])"""
    pot = po.read(cfg.pot)
    out = []
    for path in cfg.po_files():
        try:
            out.append((path.stem, path, po.read(path), None))
        except po.PoError as e:
            out.append((path.stem, path, None, str(e)))
    return pot, out


def generate(cfg: po.Config, min_completion: float, header: str) -> tuple[str, list[str]]:
    pot, catalogs = load(cfg)
    notes: list[str] = []
    source = pot.by_key()
    functions, tables, rows = [], [], []
    for code, path, catalog, error in catalogs:
        if catalog is None:
            notes.append(f"skipped {path.name}: {error}")
            continue
        errors, _, info = po.check_catalog(catalog, pot, path.name)
        for e in errors:
            notes.append(f"left out: {e}")
        completion = info["translated"] / info["total"] if info["total"] else 0.0
        if completion < min_completion or not info["valid"]:
            notes.append(f"not compiled in: {path.name} is {completion:.0%} translated (minimum {min_completion:.0%})")
            continue
        ident = "".join(ch if ch.isalnum() else "_" for ch in code)
        forms = info["forms"]
        count = forms.count if forms else 1
        expr = forms.cpp() if forms else "0ULL"
        functions.append(f"unsigned long plural_{ident}(unsigned long long n) {{ return static_cast<unsigned long>({expr}); }}")
        lines = [f"constexpr Entry entries_{ident}[] = {{"]
        for e in info["valid"]:
            src = source[e.key]
            key = e.msgid if e.msgctxt is None else f"{e.msgctxt}\x04{e.msgid}"
            plural = cxx_string(src.msgid_plural) if src.msgid_plural is not None else "{}"
            text = "\0".join(e.msgstr)
            lines.append(f"    {{{cxx_string(key)}, {plural}, {cxx_string(text)}, {'true' if src.is_format or src.msgid_plural is not None else 'false'}}},")
        lines.append("};")
        tables.append("\n".join(lines))
        name = NATIVE_NAMES.get(code.lower(), code)
        rows.append(f"    {{{{{cxx_string(code)}, {cxx_string(name)}, {completion:.3f}f}}, plural_{ident}, {count}, entries_{ident}}},")
    out = [
        "// Generated by tools/i18n_compile.py from the translation catalogs; do not edit.",
        f'#include "{header}"',
        "",
        "namespace i18n::detail {",
        "namespace {",
        "using namespace std::string_view_literals;",
        *functions,
        *tables,
    ]
    if rows:
        out += ["constexpr Catalog kCatalogs[] = {", *rows, "};", "}  // namespace", "std::span<const Catalog> catalogs() { return kCatalogs; }"]
    else:
        out += ["}  // namespace", "std::span<const Catalog> catalogs() { return {}; }"]
    out.append("}  // namespace i18n::detail")
    return "\n".join(out) + "\n", notes


def check(cfg: po.Config, min_completion: float) -> int:
    pot, catalogs = load(cfg)
    failed = False
    for code, path, catalog, error in catalogs:
        if catalog is None:
            print(f"error: {error}", file=sys.stderr)
            failed = True
            continue
        errors, warnings, info = po.check_catalog(catalog, pot, path.name)
        for w in warnings:
            print(f"warning: {w}", file=sys.stderr)
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        failed |= bool(errors)
        completion = info["translated"] / info["total"] if info["total"] else 0.0
        shipped = "compiled in" if completion >= min_completion and info["valid"] else "below the minimum, not compiled in"
        print(f"{path.name}: {info['translated']}/{info['total']} translated ({completion:.0%}), {shipped}")
    if not catalogs:
        print("no translations yet")
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--out", type=Path, help="the C++ source to write")
    parser.add_argument("--header", default="i18n.h", help="how the generated source includes i18n.h")
    parser.add_argument("--min-completion", type=float, help="overrides min_completion from i18n/i18n.json (0..1)")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    cfg = po.load_config(args.root)
    settings = json.loads((cfg.directory / "i18n.json").read_text(encoding="utf-8"))
    minimum = args.min_completion if args.min_completion is not None else float(settings.get("min_completion", 0.5))
    if args.check:
        return check(cfg, minimum)
    if not args.out:
        parser.error("give --out or --check")
    text, notes = generate(cfg, minimum, args.header)
    for n in notes:
        print(f"i18n: {n}", file=sys.stderr)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
