#!/usr/bin/env python3
"""Generate A64 OpenXR dispatch/chain metadata from the pinned SDK registry.

Usage: python tools/codegen/xr_generate.py --registry .deps/fetch/openxr_sdk-src/specification/registry/xr.xml
Generated layouts describe members (including pointer/count relationships), so
an A32 backend can add conversion instead of inheriting a memcpy assumption.
No callback-bearing or platform structure is automatically forwarded.
"""
from pathlib import Path
import argparse
import hashlib
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
FORWARD_EXT = [
    'XR_EXT_hand_tracking', 'XR_EXT_hand_joints_motion_range',
    'XR_EXT_hand_tracking_data_source', 'XR_FB_hand_tracking_aim',
    'XR_FB_hand_tracking_capsules', 'XR_FB_hand_tracking_mesh',
    'XR_META_performance_metrics', 'XR_KHR_composition_layer_depth',
    'XR_KHR_composition_layer_cylinder', 'XR_KHR_composition_layer_cube',
    'XR_KHR_composition_layer_equirect', 'XR_KHR_composition_layer_equirect2',
    'XR_KHR_composition_layer_color_scale_bias', 'XR_FB_composition_layer_image_layout',
    'XR_EXT_local_floor', 'XR_FB_space_warp',
    'XR_EXT_performance_settings', 'XR_EXT_view_configuration_depth_range',
    'XR_KHR_generic_controller', 'XR_FB_triangle_mesh',
]
MANUAL_EXT = [
    'XR_KHR_vulkan_enable', 'XR_KHR_vulkan_enable2', 'XR_KHR_loader_init',
    'XR_FB_display_refresh_rate', 'XR_FB_color_space', 'XR_FB_foveation',
    'XR_FB_foveation_configuration', 'XR_FB_swapchain_update_state',
    'XR_FB_touch_controller_pro', 'XR_META_touch_controller_plus',
    'XR_KHR_locate_spaces', 'XR_FB_haptic_pcm', 'XR_FB_haptic_amplitude_envelope',
    'XR_META_recommended_layer_resolution', 'XR_META_vulkan_swapchain_create_info',
    'XR_FB_passthrough',
]
MANUAL = set('''xrGetInstanceProcAddr xrEnumerateApiLayerProperties
xrEnumerateInstanceExtensionProperties xrCreateInstance xrDestroyInstance
xrGetInstanceProperties xrGetSystem xrGetSystemProperties xrCreateSession
xrDestroySession xrCreateReferenceSpace xrBeginSession xrEndSession xrRequestExitSession xrPollEvent xrWaitFrame xrBeginFrame
xrEndFrame xrEnumerateSwapchainFormats xrCreateSwapchain xrDestroySwapchain
xrEnumerateSwapchainImages xrAcquireSwapchainImage xrWaitSwapchainImage
xrReleaseSwapchainImage xrSuggestInteractionProfileBindings
xrGetCurrentInteractionProfile xrInitializeLoaderKHR xrCreateHandTrackerEXT
xrDestroyHandTrackerEXT xrLocateHandJointsEXT xrGetHandMeshFB xrLocateSpaces
xrGetDeviceSampleRateFB xrEnumerateBoundSourcesForAction xrApplyHapticFeedback xrStopHapticFeedback
xrCreateActionSpace xrLocateSpace'''.split())

# Action states change only in xrSyncActions, so reads between syncs reuse the
# host answer (state.cpp stored_action_state).
ACTION_READS = {'xrGetActionStateBoolean', 'xrGetActionStateFloat', 'xrGetActionStateVector2f', 'xrGetActionStatePose'}

def text(e): return ''.join(e.itertext()).strip()

def generate(registry, output, check=False):
    data = registry.read_bytes()
    xml = ET.fromstring(data)
    types = {t.get('name', t.findtext('name')): t for t in xml.findall('types/type')}
    commands = {c.get('name', c.findtext('proto/name')): c for c in xml.findall('commands/command')}
    selected, owners = set(), {}
    structures = {}
    def require(parent, owner):
        for req in parent.findall('require'):
            for c in req.findall('command'):
                name = c.get('name'); selected.add(name); owners[name] = owner
            for t in req.findall('type'):
                name = t.get('name')
                while name in types and types[name].get('alias'): name = types[name].get('alias')
                if name in types: structures[name] = owner
    require(xml.find("feature[@name='XR_VERSION_1_0']"), '')
    # 1.1 adds one loader entry point. Its KHR form is emulated on 1.0 hosts.
    selected.add('xrLocateSpaces'); owners['xrLocateSpaces'] = ''
    for ext in FORWARD_EXT + MANUAL_EXT:
        node = xml.find(f"extensions/extension[@name='{ext}']")
        if node is None: raise ValueError(ext)
        require(node, ext)
        if ext in MANUAL_EXT:
            MANUAL.update(c.get('name') for c in node.findall('require/command'))
    prefix = '// Generated by tools/codegen/xr_generate.py; do not edit.\n'
    # Hash LF-normalized text: a CRLF checkout of the same registry must give the same identity.
    prefix += f'// OpenXR registry SHA256: {hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()}\n'
    declarations, wrappers, table, layouts = [], [], [], []
    def emit(path, lines):
        content=prefix+'\n'.join(lines)+'\n'
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise RuntimeError(f'Stale generated file: {path}; run xr_generate.py without --check')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    for name in sorted(selected):
        cmd = commands[name]
        if cmd.get('alias'): cmd = commands[cmd.get('alias')]
        params = cmd.findall('param')
        signature = ', '.join(text(p) for p in params)
        args = ', '.join(p.findtext('name') for p in params)
        declarations.append(f'XrResult {name}({signature});')
        table.append(f'VENTURE_XR_COMMAND({name}, "{owners[name]}", {str(name in MANUAL).lower()})')
        if name in MANUAL: continue
        code = [f'XrResult {name}({signature}) {{', '  std::lock_guard lock(venture::hle::openxr::state().mutex);']
        if owners[name]:
            code.append(f'  if (!enabled("{owners[name]}")) return XR_ERROR_FUNCTION_UNSUPPORTED;')
        for p in params:
            typ, pname = p.findtext('type'), p.findtext('name')
            node = types.get(typ)
            if '*' in text(p) and p.get('optional') != 'true':
                length = p.get('len', '')
                # Registry lengths can be LaTeX or nested expressions. Emit
                # only scalar count relationships; retain every original in
                # metadata for future A32 conversion and deeper validation.
                if re.fullmatch(r'[A-Za-z_]\w*', length) and length != 'null-terminated':
                    code.append(f'  if ({length} && !{pname}) return XR_ERROR_VALIDATION_FAILURE;')
                elif not length or length == 'null-terminated':
                    code.append(f'  if (!{pname}) return XR_ERROR_VALIDATION_FAILURE;')
            if node is not None and node.get('category') == 'handle' and '*' not in text(p):
                code.append(f'  if (!valid_handle({pname}, "{typ}")) return XR_ERROR_HANDLE_INVALID;')
            if node is not None and node.get('category') == 'struct':
                member = node.find("member[name='type']")
                if member is not None and member.get('values') and p.get('len') is None:
                    optional = p.get('optional') == 'true'
                    code.append(f'  if ({"!" if not optional else ""}{pname}{" &&" if optional else " ||"} XR_FAILED(validate_struct({pname}, {member.get("values")}))) return XR_ERROR_VALIDATION_FAILURE;')
                # Root structures referenced by core commands also get layouts.
                structures.setdefault(typ, owners[name])
        if name.startswith('xrDestroy'):
            # An asynchronous host xrEndFrame may still reference the object.
            code.append('  venture::xr::session().finish_host_end();')
        if name in ('xrDestroyAction', 'xrDestroyActionSet'):
            code.append(f'  cancel_handle_haptics({params[0].findtext("name")});')
        if name == 'xrAttachSessionActionSets':
            code.append('  auto result = venture::xr::attach_with_menu_chord(session, attachInfo);')
        elif name == 'xrSyncActions':
            code.append('  auto result = venture::xr::sync_with_menu_chord(session, syncInfo);')
        elif name in ACTION_READS:
            code.append(f'  auto result = stored_action_state<PFN_{name}, "{name}">({args});')
        elif name == 'xrCreateAction':
            code.append(f'  auto result = create_action_for_host({args});')
        else:
            code.append(f'  auto result = host_call<PFN_{name}, "{name}">({args});')
        if name in ('xrSyncActions', 'xrAttachSessionActionSets'):
            code.append('  forget_action_states();')
        if name == 'xrGetActionStateBoolean':
            code.append('  if (XR_SUCCEEDED(result)) venture::xr::menu_action_state(session, getInfo, state);')
        if name.startswith('xrCreate'):
            last = params[-1]; typ = last.findtext('type'); pname = last.findtext('name')
            if types.get(typ) is not None and types[typ].get('category') == 'handle':
                parent = params[0].findtext('name')
                code.append(f'  if (XR_SUCCEEDED(result)) track_handle(*{pname}, "{typ}", {parent});')
        if name.startswith('xrDestroy'):
            code.append(f'  if (XR_SUCCEEDED(result)) forget_handle({params[0].findtext("name")});')
        if name == 'xrCreateAction':
            code.append('  if (XR_SUCCEEDED(result)) venture::xr::register_menu_action(actionSet, *action);')
            code.append('  if (XR_SUCCEEDED(result)) { auto &a = state().actions[*action]; a.type = createInfo->actionType; if (createInfo->countSubactionPaths) a.subactions.assign(createInfo->subactionPaths, createInfo->subactionPaths + createInfo->countSubactionPaths); }')
        if name == 'xrAttachSessionActionSets':
            code.append('  if (XR_SUCCEEDED(result)) { venture::xr::clear_haptic_bindings(session); for (uint32_t i = 0; i < attachInfo->countActionSets; ++i) state().attached_sets[session].insert(key(attachInfo->actionSets[i])); }')
        if name == 'xrLocateViews':
            code.append('  if (XR_SUCCEEDED(result) && views) sanitize_views(*viewState, std::min(viewCapacityInput, *viewCountOutput), views);')
        code += ['  return result;', '}']
        if name in ('xrLocateViews', 'xrSyncActions'):
            code = [code[0], f'  xr_call_trace::Call trace("guest.{name}");',
                    '  return trace.finish([&]() -> XrResult {', *code[1:-1], '  }());', code[-1]]
        wrappers.extend(code)
    for name, owner in sorted(structures.items()):
        typ = types[name]
        if typ.get('category') != 'struct' or typ.get('alias'): continue
        if any('PFN_' in text(m) for m in typ.findall('member')): continue
        members = typ.findall('member')
        stype = typ.find("member[name='type']")
        if stype is None or not stype.get('values'): continue
        layouts.append(f'VENTURE_XR_STRUCT({name}, {stype.get("values")}, "{owner}", "{typ.get("structextends", "")}")')
        for m in members:
            mname = m.findtext('name')
            layouts.append(f'VENTURE_XR_MEMBER({name}, {mname}, "{m.findtext("type")}", {str("*" in text(m)).lower()}, "{m.get("len", "")}")')
    output.mkdir(parents=True, exist_ok=True)
    for name, lines in [('declarations.inc', declarations), ('forward.inc', wrappers),
                        ('commands.inc', table), ('structures.inc', layouts)]:
        emit(output / name, lines)
    mock = ROOT / 'tests/mock_openxr_runtime'
    if (mock / 'runtime.cpp').exists():
        implemented = set(re.findall(r'XrResult\s+m_(xr\w+)\(', (mock / 'runtime.cpp').read_text()))
        lines, entries = [], []
        for name in sorted(selected):
            cmd = commands[name]
            if cmd.get('alias'): cmd = commands[cmd.get('alias')]
            params = cmd.findall('param')
            sig = ', '.join(text(p) for p in params)
            args = ', '.join(p.findtext('name') for p in params)
            lines.append(f'XrResult XRAPI_CALL dispatch_{name}({sig}) {{')
            # WaitFrame releases its state lock while pacing a real-time mock, and
            # a gated EndFrame (ventureMockXrGateEnd) while it is held.
            if name not in ('xrWaitFrame', 'xrEndFrame'):
                lines.append('  std::lock_guard lock(mutex);')
            lines.append(f'  return m_{name}({args});' if name in implemented else '  return XR_ERROR_FUNCTION_UNSUPPORTED;')
            lines.append('}')
            entries.append(f'  {{"{name}", reinterpret_cast<PFN_xrVoidFunction>(&dispatch_{name})}},')
        lines.append('struct Entry { const char* name; PFN_xrVoidFunction function; };')
        lines.append('const Entry dispatch[]{')
        lines += entries + ['};']
        emit(mock / 'dispatch.inc', lines)

if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--registry', type=Path, required=True)
    p.add_argument('--output', type=Path, default=ROOT / 'src/runtime/hle/openxr/generated')
    p.add_argument('--check', action='store_true')
    a = p.parse_args(); generate(a.registry, a.output, a.check)
