// Venture: writes the resource IDs layoutlib's framework classes were compiled
// with, so tools/layoutlib/framework_res.py can build a framework-res.apk whose
// resources.arsc matches them exactly. layoutlib's com.android.internal.R holds
// every framework resource its code references; javac inlined those IDs into
// View, TextView, PhoneWindow and the rest, so the table must use the same ones.
//
// Usage: java FrameworkResourceIds.java <layoutlib.jar> <stable-ids.txt> <staging.xml> [names.txt]
//
// names.txt lists the framework's resource names (type/name per line): R field
// names spell a dot as an underscore (Widget_Material for Widget.Material).
//
// stable-ids.txt is aapt2's --stable-ids format. Resources in a staged type ID
// (a second type ID with the same type name, API levels in development) cannot
// be expressed there; they go to staging.xml as <staging-public-group> entries
// in ID order, with placeholder resources filling any gaps.
import java.io.File;
import java.io.PrintWriter;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

public class FrameworkResourceIds {
  public static void main(String[] args) throws Exception {
    if (args.length != 3 && args.length != 4)
      throw new IllegalArgumentException("layoutlib.jar stable-ids.txt staging.xml [names.txt]");
    Map<String, String> spelled = new HashMap<>();
    if (args.length == 4)
      for (String line : java.nio.file.Files.readAllLines(java.nio.file.Path.of(args[3]))) {
        int slash = line.indexOf('/');
        if (slash > 0)
          spelled.put(line.substring(0, slash) + "/" + line.substring(slash + 1).replace('.', '_'), line.substring(slash + 1));
      }
    TreeMap<Integer, String[]> ids = new TreeMap<>();
    try (URLClassLoader loader = new URLClassLoader(new URL[] {new File(args[0]).toURI().toURL()}, null)) {
      Class<?> r = Class.forName("com.android.internal.R", false, loader);
      for (Class<?> inner : r.getDeclaredClasses()) {
        String type = inner.getSimpleName();
        if (type.equals("styleable")) continue;
        for (Field field : inner.getDeclaredFields()) {
          if (field.getType() != int.class || !Modifier.isStatic(field.getModifiers())) continue;
          field.setAccessible(true);
          ids.put(field.getInt(null),
              new String[] {type, spelled.getOrDefault(type + "/" + field.getName(), field.getName())});
        }
      }
    }
    // The type ID most of a type's resources use is its own; any other is staged,
    // except private attributes, which aapt2 keeps in their own "^attr-private" type.
    Map<String, Map<Integer, Integer>> counts = new HashMap<>();
    for (var entry : ids.entrySet())
      counts.computeIfAbsent(entry.getValue()[0], k -> new HashMap<>())
          .merge((entry.getKey() >>> 16) & 0xff, 1, Integer::sum);
    Map<String, Integer> primary = new HashMap<>();
    for (var entry : counts.entrySet())
      primary.put(entry.getKey(), entry.getValue().entrySet().stream()
          .max(Map.Entry.comparingByValue()).orElseThrow().getKey());
    int attrPrivate = -1;
    for (var entry : counts.getOrDefault("attr", Map.of()).entrySet()) {
      int typeId = entry.getKey();
      // Private attributes follow the last ordinary type below the staged range.
      if (typeId != primary.get("attr") && typeId < 0x80) attrPrivate = typeId;
    }
    TreeMap<Integer, List<Map.Entry<Integer, String[]>>> staged = new TreeMap<>();
    try (PrintWriter stable = new PrintWriter(args[1], "UTF-8")) {
      for (var entry : ids.entrySet()) {
        String type = entry.getValue()[0];
        int typeId = (entry.getKey() >>> 16) & 0xff;
        if (type.equals("attr") && typeId == attrPrivate) type = "^attr-private";
        else if (typeId != primary.get(type)) {
          staged.computeIfAbsent(typeId, k -> new ArrayList<>()).add(entry);
          continue;
        }
        stable.printf("android:%s/%s = 0x%08x%n", type, entry.getValue()[1], entry.getKey());
      }
    }
    try (PrintWriter xml = new PrintWriter(args[2], "UTF-8")) {
      xml.println("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
      xml.println("<!-- Generated by tools/layoutlib/FrameworkResourceIds.java -->");
      xml.println("<resources>");
      int gap = 0;
      List<String> placeholders = new ArrayList<>();
      for (var group : staged.entrySet()) {
        var entries = group.getValue();
        String type = entries.get(0).getValue()[0];
        int first = (0x01 << 24) | (group.getKey() << 16);
        xml.printf("  <staging-public-group type=\"%s\" first-id=\"0x%08x\">%n", type, first);
        int next = first;
        for (var entry : entries) {
          for (; next < entry.getKey(); ++next) {
            String name = "venture_staged_gap_" + gap++;
            xml.printf("    <public name=\"%s\" />%n", name);
            placeholders.add(placeholder(type, name));
          }
          xml.printf("    <public name=\"%s\" />%n", entry.getValue()[1]);
          ++next;
        }
        xml.println("  </staging-public-group>");
      }
      for (String placeholder : placeholders) xml.println("  " + placeholder);
      xml.println("</resources>");
    }
    System.out.printf("%d framework resource IDs, %d staged groups%n", ids.size(), staged.size());
  }

  static String placeholder(String type, String name) {
    return switch (type) {
      case "attr" -> "<attr name=\"" + name + "\" format=\"boolean\" />";
      case "color" -> "<color name=\"" + name + "\">#00000000</color>";
      case "string" -> "<string name=\"" + name + "\" translatable=\"false\"></string>";
      case "array" -> "<array name=\"" + name + "\" />";
      default -> "<item type=\"" + type + "\" name=\"" + name + "\" format=\"integer\">0</item>";
    };
  }
}
