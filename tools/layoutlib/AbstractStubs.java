// Venture: writes a Java class that implements every abstract method of a
// layoutlib class by throwing UnsupportedOperationException, so a Venture
// implementation (src/runtime/layoutlib/java) overrides only what it serves.
//
// Usage: java -cp layoutlib.jar AbstractStubs.java <class> <output class> > Output.java
//        java -cp layoutlib.jar AbstractStubs.java <interface> <output class> wrapper > Output.java
// The wrapper form writes a class that passes every method of the interface,
// default methods too, to a target instance (AOSP's InputConnectionWrapper).
// Rerun after a layoutlib update; javac reports a stale file as a missing method.
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

public class AbstractStubs {
  public static void main(String[] args) throws Exception {
    Class<?> base = Class.forName(args[0], false, AbstractStubs.class.getClassLoader());
    String output = args[1];
    boolean wrapper = args.length > 2 && args[2].equals("wrapper");
    int dot = output.lastIndexOf('.');
    Map<String, Method> methods = new LinkedHashMap<>();
    for (Class<?> c = base; c != null; c = c.getSuperclass())
      for (Method m : c.getDeclaredMethods()) {
        String key = m.getName() + java.util.Arrays.toString(m.getParameterTypes());
        if (!methods.containsKey(key)) methods.put(key, m);
      }
    List<Method> stubs = new ArrayList<>();
    for (Method m : methods.values())
      if (wrapper ? !Modifier.isStatic(m.getModifiers()) && !m.isSynthetic() : Modifier.isAbstract(m.getModifiers())) stubs.add(m);
    stubs.sort(Comparator.comparing((Method m) -> m.getName()).thenComparing(m -> java.util.Arrays.toString(m.getParameterTypes())));
    StringBuilder out = new StringBuilder();
    out.append("// Generated by tools/layoutlib/AbstractStubs.java from layoutlib's ").append(base.getName()).append(".\n");
    out.append("// Do not edit: rerun the tool after a layoutlib update.\n");
    out.append("package ").append(output, 0, dot).append(";\n\n");
    out.append("@SuppressWarnings({\"deprecation\", \"unchecked\", \"rawtypes\"})\n");
    String simple = output.substring(dot + 1);
    if (wrapper) {
      out.append("public class ").append(simple).append(" implements ").append(name(base)).append(" {\n");
      out.append("  private ").append(name(base)).append(" mTarget;\n");
      out.append("  private final boolean mMutable;\n");
      out.append("  public ").append(simple).append("(").append(name(base)).append(" target, boolean mutable) {\n");
      out.append("    mMutable = mutable;\n    mTarget = target;\n  }\n");
      out.append("  public void setTarget(").append(name(base)).append(" target) {\n");
      out.append("    if (mTarget != null && !mMutable) throw new SecurityException(\"not mutable\");\n");
      out.append("    mTarget = target;\n  }\n");
    } else {
      out.append("public abstract class ").append(simple).append(" extends ").append(name(base)).append(" {\n");
    }
    for (Method m : stubs) {
      String visibility = Modifier.isPublic(m.getModifiers()) ? "public " : Modifier.isProtected(m.getModifiers()) ? "protected " : "";
      out.append("  @Override ").append(visibility);
      TypeVariable<Method>[] variables = m.getTypeParameters();
      if (variables.length > 0)
        out.append('<').append(java.util.Arrays.stream(variables).map(AbstractStubs::variable).collect(Collectors.joining(", "))).append("> ");
      out.append(type(m.getGenericReturnType())).append(' ').append(m.getName()).append('(');
      Type[] params = m.getGenericParameterTypes();
      for (int i = 0; i < params.length; ++i) {
        if (i > 0) out.append(", ");
        String t = type(params[i]);
        if (m.isVarArgs() && i == params.length - 1) t = t.substring(0, t.length() - 2) + "...";
        out.append(t).append(" a").append(i);
      }
      out.append(')');
      Class<?>[] thrown = m.getExceptionTypes();
      if (thrown.length > 0)
        out.append(" throws ").append(java.util.Arrays.stream(thrown).map(AbstractStubs::name).collect(Collectors.joining(", ")));
      if (wrapper) {
        out.append(" {\n    ").append(m.getReturnType() == void.class ? "" : "return ").append("mTarget.").append(m.getName()).append('(');
        for (int i = 0; i < params.length; ++i) out.append(i > 0 ? ", a" : "a").append(i);
        out.append(");\n  }\n");
      } else {
        out.append(" {\n    throw new UnsupportedOperationException(\"").append(m.getName()).append("\");\n  }\n");
      }
    }
    out.append("}\n");
    System.out.print(out);
  }

  static String variable(TypeVariable<?> v) {
    Type[] bounds = v.getBounds();
    if (bounds.length == 1 && bounds[0] == Object.class) return v.getName();
    return v.getName() + " extends " + java.util.Arrays.stream(bounds).map(AbstractStubs::type).collect(Collectors.joining(" & "));
  }

  static String type(Type t) {
    return t.getTypeName().replace('$', '.');
  }

  static String name(Class<?> c) {
    return c.getName().replace('$', '.');
  }
}
