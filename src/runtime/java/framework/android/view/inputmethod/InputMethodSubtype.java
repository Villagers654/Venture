package android.view.inputmethod;
/** The en-US keyboard subtype of the framework's logical keyboard. */
public final class InputMethodSubtype {
  public String getLocale() { return "en_US"; }
  public String getLanguageTag() { return "en-US"; }
  public String getMode() { return "keyboard"; }
  public String getExtraValue() { return ""; }
  public boolean isAuxiliary() { return false; }
}
