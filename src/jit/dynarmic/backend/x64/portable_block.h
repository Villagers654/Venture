// Venture: portable blocks. A compiled block is captured with every reference
// whose bytes depend on where the code, its JIT or its process lives, so a
// later JIT (another thread or another process) can install the same machine
// code instead of translating the guest code again.

#pragma once

#include <array>
#include <cstddef>
#include <optional>
#include <span>
#include <string>
#include <vector>

#include "common/common_types.h"
#include "dynarmic/backend/x64/abi.h"
#include "dynarmic/backend/x64/xbyak.h"

namespace Dynarmic::Backend::X64 {

/// What a reference points at, independent of any one JIT's addresses.
enum class PortableRefKind : u8 {
    Hot,       // value: offset in the block's hot part
    Cold,      // value: offset in the block's cold part
    Symbol,    // aux: PortableSymbol (an entry point the JIT generated before any block)
    Constant,  // value: index into PortableBlock::constants
    Fallback,  // value: packed fastmem fallback key (FallbackKey)
    Host,      // aux: index into PortableBlock::modules; value: offset in that module's image
    Object,    // aux: PortableObject; value: offset from that object's address
    SiteSlot,  // value: dispatch site slot index << 8 | byte offset in the slot
    Svc,       // value: guest PC; aux: SVC immediate (the user's metadata for that call)
    UnlinkedExit,  // value: IR::LocationDescriptor whose unlinked exit stub is referenced
};

/// Entry points generated by every JIT before its first block.
enum class PortableSymbol : u16 {
    ReturnFromRunCode0,
    ReturnFromRunCode1,
    ReturnFromRunCode2,
    ReturnFromRunCode3,
    PopRSBHint,
    FastDispatchHint,
    FastDispatchMiss,
    RSBMiss,
    RSBPopLookup,
    SiteMiss,
    FastDispatchLookup,
    MemoryRead128,
    MemoryWrite128,
    MemoryExclusiveWrite128,
    Count,
};

/// Per-JIT (or per-process) objects whose address code may embed.
enum class PortableObject : u16 {
    Callbacks,
    Emitter,
    JitInterface,
    FastDispatchTable,
    Tpidr,
    Tpidrro,
    MonitorLock,
    MonitorActiveCount,
    MonitorAddressBase,
    MonitorGenerationBase,
    MonitorAddressSelf,
    MonitorValueSelf,
    MonitorGenerationSelf,
    Count,
};

struct PortableRef {
    PortableRefKind kind{};
    u16 aux = 0;
    u64 value = 0;
    bool operator==(const PortableRef&) const = default;
};

struct PortableReloc {
    u32 site = 0;       // offset in its part
    bool cold = false;  // site part
    u8 size = 0;        // 1 or 4: displacement; 8: absolute address
    s32 addend = 0;     // displacement: stored = target - site + addend
    PortableRef target;
    bool operator==(const PortableReloc&) const = default;
};

/// A block link site (EmitPatchJg/Jz/Jmp/MovRcx); installation re-emits it.
struct PortableLink {
    enum class Type : u8 { Jg, Jz, Jmp, MovRcx };
    u32 site = 0;  // hot offset
    Type type{};
    u64 target = 0;  // IR::LocationDescriptor value
    bool operator==(const PortableLink&) const = default;
};
/// Bytes a compact link site occupies (EmitPatch* with EnsurePatchLocationSize).
constexpr size_t LinkSiteSize(PortableLink::Type type) {
    return type == PortableLink::Type::MovRcx ? 10 : type == PortableLink::Type::Jmp ? 5 : 6;
}

struct PortableFastmem {
    PortableRef location;  // Hot or Cold
    PortableRef resume;
    PortableRef callback;
    u64 marker_descriptor = 0;
    u32 marker_index = 0;
    bool recompile = false;
    bool operator==(const PortableFastmem&) const = default;
};

struct PortableUnwind {
    u32 begin = 0, end = 0;  // hot offsets
    bool inherits_run_frame = false;
    std::vector<ABIPrologue::Operation> operations;
};

struct PortableBlock {
    u64 descriptor = 0;
    u32 size = 0;  // the BlockDescriptor size (hot bytes from the entry point)
    /// PortableCodeHash of the guest code in `ranges` when the block was captured.
    u64 code_hash = 0;
    std::vector<u8> hot, cold;
    std::vector<PortableReloc> relocs;
    std::vector<PortableLink> links;
    std::vector<PortableFastmem> fastmem;
    std::vector<PortableUnwind> unwind;
    std::vector<std::pair<u64, u64>> ranges;  // closed guest intervals
    std::vector<std::array<u64, 2>> constants;
    std::vector<std::string> modules;
};

/// A hash of guest instruction words, fed one at a time in range order.
struct PortableCodeHash {
    u64 state = 0xcbf29ce484222325ull;
    void Add(u32 word) {
        state = (state ^ word) * 0x100000001b3ull;
        state ^= state >> 29;
    }
};

std::vector<u8> SerializePortableBlock(const PortableBlock& block);
std::optional<PortableBlock> DeserializePortableBlock(std::span<const u8> bytes);
/// Reuses `block`'s storage (a JIT installs from one scratch block); false when invalid.
bool DeserializePortableBlock(std::span<const u8> bytes, PortableBlock& block);
/// Bytes with every relocated or re-emitted field cleared, for comparing two
/// captures of the same guest code.
std::vector<u8> NormalizedPortableBytes(const PortableBlock& block, bool cold);

/// Empty when two serialized captures of one block are equivalent, else the first difference.
std::string ComparePortableBlocks(std::span<const u8> expected, std::span<const u8> actual);
/// Counts an outcome of capture or installation (diagnostics).
void PortableStat(const char* outcome);
/// Adds the duration of one install (or one translation, `installed` false).
void PortableTime(bool installed, long long nanoseconds);
/// "outcome count, ..." for every outcome so far.
std::string PortableStatsReport();

/// A loaded host image: the emitter's helpers and static tables live in these.
struct HostModule {
    std::string name;
    u64 begin = 0, end = 0;
};
const std::vector<HostModule>& HostModules();
std::optional<std::pair<size_t, u64>> FindHostModule(u64 address);

/// Records encoded references while one block is emitted (Xbyak observer).
class PortableCapture final : public Xbyak::RelocationObserver {
public:
    struct Range {
        u64 begin, end;
        PortableRefKind kind;
        u16 aux;
    };
    /// Addresses the emitter may embed: objects, tables and host images.
    std::vector<Range> ranges;

    struct Event {
        enum class Type : u8 { Absolute, Label, LabelAddress, Imm64 } type;
        u8 size;
        size_t site;
        u64 target;  // absolute address, or code offset for labels
    };
    std::vector<Event> events;
    struct Svc {
        size_t site;
        u64 pc;
        u32 imm;
    };
    std::vector<Svc> svcs;
    struct Link {
        size_t site;
        PortableLink::Type type;
        u64 target;
    };
    std::vector<Link> links;
    struct Fastmem {
        u64 location, resume, callback, marker_descriptor;
        u32 marker_index;
        bool recompile;
    };
    std::vector<Fastmem> fastmem;
    struct Unwind {
        const void* begin;
        const void* end;
        ABIPrologue prologue;
        bool inherits_run_frame;
    };
    std::vector<Unwind> unwind;
    /// Diagnostics: 64-bit immediates outside every range, embedded as they are.
    std::vector<u64> unclassified;
    /// Set when the block contains something capture cannot express.
    const char* failure = nullptr;

    void Reset();
    void SortRanges();
    const Range* FindRange(u64 address) const;

    void onAbsolute(size_t site, int size, const uint8_t* target) override;
    void onLabel(size_t site, int size, size_t target) override;
    void onLabelAddress(size_t site, int size, size_t target) override;
    void onRipDisplacement(size_t site) override;
    bool isAddress(uint64_t value) override;
    void onImm64(size_t site, uint64_t value) override;
};

}  // namespace Dynarmic::Backend::X64
